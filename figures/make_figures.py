#!/usr/bin/env python3
r"""Generate the data-driven TikZ figures of the paper.

Run from the folder `figures/`:  python3 make_figures.py
Writes fig_model.tex, fig_polygon.tex, fig_recursion.tex, fig_boundary.tex.
The figure fig_angular_deletion.tex is drawn by hand.
All geometry is computed here (no eyeballing); the asserts check that the
displayed configurations satisfy the inequalities used in the proofs.
"""
import math
import random

OUT = {}


def f(x):
    return f"{x:.3f}"


# ---------------------------------------------------------------------------
# Figure 1: the model (numerical illustration)
# ---------------------------------------------------------------------------
def fig_model(seed=10, mu=0.6, lam=1.4, r=0.5, W=12.0, H=7.0):
    rng = random.Random(seed)
    cx, cy = W / 2, H / 2
    rho = math.hypot(W, H) / 2
    # Poisson lines hitting the disk B((cx,cy), rho): count ~ Poisson(2 mu rho)
    mean = 2 * mu * rho
    # Poisson sampling by inversion
    n, p, u = 0, math.exp(-mean), rng.random()
    cdf = p
    while u > cdf:
        n += 1
        p *= mean / n
        cdf += p
    lines, points = [], []
    for _ in range(n):
        th = rng.uniform(0, math.pi)
        s = (cx * math.cos(th) + cy * math.sin(th)) + rng.uniform(-rho, rho)
        nx, ny = math.cos(th), math.sin(th)
        # foot point and direction
        px, py = s * nx, s * ny
        dx, dy = -ny, nx
        # parameter interval of the chord in the bounding disk
        t0 = (cx - px) * dx + (cy - py) * dy
        half = math.sqrt(max(rho ** 2 - ((px - cx) ** 2 + (py - cy) ** 2 - t0 ** 2), 0))
        a, b = t0 - half, t0 + half
        lines.append(((px + a * dx, py + a * dy), (px + b * dx, py + b * dy)))
        # Poisson points of intensity lam per unit length on the chord
        t = a
        while True:
            t += rng.expovariate(lam)
            if t > b:
                break
            x, y = px + t * dx, py + t * dy
            if 0 <= x <= W and 0 <= y <= H:
                points.append((x, y))
    # connected components of the union of disks of radius r (within window)
    parent = list(range(len(points)))

    def find(i):
        while parent[i] != i:
            parent[i] = parent[parent[i]]
            i = parent[i]
        return i

    for i in range(len(points)):
        for j in range(i + 1, len(points)):
            if math.dist(points[i], points[j]) < 2 * r:
                parent[find(i)] = find(j)
    comps = {}
    for i in range(len(points)):
        comps.setdefault(find(i), []).append(i)
    largest = max(comps.values(), key=len)
    big = set(largest)
    out = [r"% Generated by make_figures.py (fig_model) -- do not edit by hand.",
           f"% seed={seed}, mu={mu}, lambda={lam}, r={r}, window=[0,{W}]x[0,{H}]",
           f"% {n} lines meet the bounding disk, {len(points)} points in the window,",
           f"% largest component: {len(largest)} points, {len(comps)} components.",
           r"\begin{tikzpicture}[x=0.95cm,y=0.95cm]",
           r"  \begin{scope}",
           f"    \\clip (0,0) rectangle ({W},{H});"]
    for (p0, p1) in lines:
        out.append(f"    \\draw[gray!55, thin] ({f(p0[0])},{f(p0[1])}) -- ({f(p1[0])},{f(p1[1])});")
    for i, (x, y) in enumerate(points):
        col = "retainedfill" if i in big else "gray!25"
        out.append(f"    \\fill[{col}, opacity=0.75] ({f(x)},{f(y)}) circle ({r});")
    for i, (x, y) in enumerate(points):
        col = "retained" if i in big else "gray!70!black"
        out.append(f"    \\fill[{col}] ({f(x)},{f(y)}) circle (0.045);")
    out += [r"  \end{scope}",
            f"  \\draw (0,0) rectangle ({W},{H});",
            # scale bar for r
            f"  \\draw[|-|] ({W - 1.6},-0.3) -- ({W - 1.6 + r},-0.3) node[right, font=\\small] {{$r$}};",
            r"\end{tikzpicture}"]
    OUT["fig_model.tex"] = "\n".join(out) + "\n"
    return dict(n=n, npts=len(points), big=len(largest), comps=len(comps))


