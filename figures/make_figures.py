# Figure 3: extraction of two crossings (Proposition 3.2), L = 1, a = 6
# ---------------------------------------------------------------------------
def first_exit(path, c, half):
    """Follow the polyline from path[0] until it first meets the boundary of
    the square c + [-half, half]^2; return the subpath."""
    def linf(p):
        return max(abs(p[0] - c[0]), abs(p[1] - c[1]))
    sub = [path[0]]
    for p, q in zip(path, path[1:]):
        if linf(q) < half:
            sub.append(q)
            continue
        lo, hi = 0.0, 1.0
        for _ in range(60):
            mid = (lo + hi) / 2
            m = (p[0] + mid * (q[0] - p[0]), p[1] + mid * (q[1] - p[1]))
            if linf(m) < half:
                lo = mid
            else:
                hi = mid
        sub.append((p[0] + hi * (q[0] - p[0]), p[1] + hi * (q[1] - p[1])))
        return sub
    raise ValueError("path does not leave the square")


def fig_recursion():
    L, a = 1.0, 6
    R = a * L
    path = [(-3.0, -1.5), (-1.0, 0.5), (1.5, 0.0), (2.5, 2.5), (4.5, 3.0), (5.0, 4.5),
            (6.0, 4.6), (7.2, 5.6), (7.6, 7.4), (9.4, 8.0), (10.2, 9.6), (11.2, 10.0), (12.0, 10.3)]
    iu = 6  # u = path[6] on boundary of Q_R
    u, v = path[iu], path[-1]
    assert abs(max(abs(u[0]), abs(u[1])) - R) < 1e-9
    assert abs(max(abs(v[0]), abs(v[1])) - 2 * R) < 1e-9
    for p in path[:iu]:
        assert max(abs(p[0]), abs(p[1])) < 2 * R
    x = (round(u[0] / L) * L, round(u[1] / L) * L)
    y = (round(v[0] / L) * L, round(v[1] / L) * L)
    assert max(abs(x[0] - y[0]), abs(x[1] - y[1])) >= (a - 1) * L
    seg = path[iu:]
    sx = first_exit(seg, x, 2 * L)
    sy = first_exit(seg[::-1], y, 2 * L)

    def poly(ps):
        return " -- ".join(f"({f(p[0])},{f(p[1])})" for p in ps)

    out = [r"% Generated by make_figures.py (fig_recursion) -- do not edit by hand.",
           r"% L = 1, a = 6 (in the proof a >= 2^20); schematic path.",
           r"\begin{tikzpicture}[x=0.4cm,y=0.4cm]",
           r"  \begin{scope}",
           r"    \clip (-14.5,-13) rectangle (15.5,15.5);",
           r"    \foreach \i in {-18,...,18} \foreach \j in {-18,...,18} \fill[gray!45] (\i,\j) circle (0.06);",
           r"  \end{scope}",
           r"  \node[anchor=south west, font=\small] at (-6,-6) {$Q_R$};",
           r"  \node[anchor=south west, font=\small] at (-12,-12) {$Q_{2R}$};"]
    for c in (x, y):
        out.append(f"  \\fill[retainedfill!45] ({c[0]-3},{c[1]-3}) rectangle ({c[0]+3},{c[1]+3});")
    out.append(r"  \draw[thick] (-6,-6) rectangle (6,6);")
    out.append(r"  \draw[thick] (-12,-12) rectangle (12,12);")
    for c, name, pos in ((x, "x", "above right"), (y, "y", "below right")):
        out.append(f"  \\draw[gray, dashed] ({c[0]-3},{c[1]-3}) rectangle ({c[0]+3},{c[1]+3});")
        out.append(f"  \\draw[retained] ({c[0]-2},{c[1]-2}) rectangle ({c[0]+2},{c[1]+2});")
        out.append(f"  \\draw[retained] ({c[0]-1},{c[1]-1}) rectangle ({c[0]+1},{c[1]+1});")
        out.append(f"  \\fill[retained] ({c[0]},{c[1]}) circle (0.18) node[{pos}=-2pt, font=\\small] {{${name}$}};")
    out.append(f"  \\draw[deleted, densely dashed, thick] {poly(path)};")
    out.append(f"  \\draw[deleted, line width=1.6pt] {poly(sx)};")
    out.append(f"  \\draw[deleted, line width=1.6pt] {poly(sy)};")
    out.append(f"  \\fill[black] ({f(u[0])},{f(u[1])}) circle (0.2) node[below left=-2pt, font=\\small] {{$u$}};")
    out.append(f"  \\fill[black] ({f(v[0])},{f(v[1])}) circle (0.2) node[above left=-1pt, font=\\small] {{$v$}};")
    out.append(r"  \node[font=\scriptsize, anchor=north] at (%s,%s) {$Q_{3L}(x)$};" % (f(x[0]), f(x[1] - 3)))
    out.append(r"  \node[font=\scriptsize, anchor=south] at (%s,%s) {$Q_{3L}(y)$};" % (f(y[0]), f(y[1] + 3)))
    out.append(r"\end{tikzpicture}")
    OUT["fig_recursion.tex"] = "\n".join(out) + "\n"
    return dict(x=x, y=y)


