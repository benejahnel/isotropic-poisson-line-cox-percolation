SHAPE = """
...............
....XXXXX......
...XX...XX.....
..XX.....XX....
..X.......X....
..X.......XXX..
..XX........X..
...X.......XX..
...XXX..XXXX...
.....XXXX......
...............
"""


def hull(ps):
    ps = sorted(set(ps))

    def cross(o, a, b):
        return (a[0] - o[0]) * (b[1] - o[1]) - (a[1] - o[1]) * (b[0] - o[0])
    lo, up = [], []
    for p in ps:
        while len(lo) >= 2 and cross(lo[-2], lo[-1], p) <= 0:
            lo.pop()
        lo.append(p)
    for p in reversed(ps):
        while len(up) >= 2 and cross(up[-2], up[-1], p) <= 0:
            up.pop()
        up.append(p)
    return lo[:-1] + up[:-1]


def fig_boundary():
    rows = [r for r in SHAPE.strip("\n").split("\n")]
    nr = len(rows)
    S = {(j, nr - 1 - i) for i, row in enumerate(rows) for j, ch in enumerate(row) if ch == "X"}
    nb4 = ((1, 0), (-1, 0), (0, 1), (0, -1))
    # S nearest-neighbour connected
    start = next(iter(S))
    seen, stack = {start}, [start]
    while stack:
        p = stack.pop()
        for d in nb4:
            q = (p[0] + d[0], p[1] + d[1])
            if q in S and q not in seen:
                seen.add(q)
                stack.append(q)
    assert seen == S
    xs = [p[0] for p in S]
    ys = [p[1] for p in S]
    box = (min(xs) - 2, max(xs) + 2, min(ys) - 2, max(ys) + 2)

    def inbox(p):
        return box[0] <= p[0] <= box[1] and box[2] <= p[1] <= box[3]
    # unbounded component U (within the box, seeded at a corner)
    U, stack = {(box[0], box[2])}, [(box[0], box[2])]
    while stack:
        p = stack.pop()
        for d in nb4:
            q = (p[0] + d[0], p[1] + d[1])
            if inbox(q) and q not in S and q not in U:
                U.add(q)
                stack.append(q)
    T = {q for p in S for d in nb4 for q in [(p[0] + d[0], p[1] + d[1])] if q in U}
    holes = {(i, j) for i in range(box[0], box[1] + 1) for j in range(box[2], box[3] + 1)
             if (i, j) not in S and (i, j) not in U}
    # star-connectedness of T
    start = next(iter(T))
    seen, stack = {start}, [start]
    while stack:
        p = stack.pop()
        for dx in (-1, 0, 1):
            for dy in (-1, 0, 1):
                q = (p[0] + dx, p[1] + dy)
                if q in T and q not in seen:
                    seen.add(q)
                    stack.append(q)
    assert seen == T
    hS, hT = hull(S), hull(T)
    # star edges within T
    E = set()
    for p in T:
        for dx in (-1, 0, 1):
            for dy in (-1, 0, 1):
                q = (p[0] + dx, p[1] + dy)
                if q in T and dx != 0 and dy != 0 and (p[0] + dx, p[1]) not in T and (p[0], p[1] + dy) not in T:
                    E.add(tuple(sorted((p, q))))
    out = [r"% Generated by make_figures.py (fig_boundary) -- do not edit by hand.",
           r"% S: finite open cluster (shape chosen by hand), T: exterior boundary.",
           r"\begin{tikzpicture}[x=0.55cm,y=0.55cm]"]
    for (i, j) in S:
        out.append(f"  \\fill[retainedfill] ({i-0.5},{j-0.5}) rectangle ++(1,1);")
    for (i, j) in T:
        out.append(f"  \\fill[deleted!25] ({i-0.5},{j-0.5}) rectangle ++(1,1);")
    for (i, j) in holes:
        out.append(f"  \\draw[gray!60, very thin] ({i-0.5},{j-0.5}) rectangle ++(1,1);")
    for (i, j) in S | T:
        out.append(f"  \\draw[gray!60, very thin] ({i-0.5},{j-0.5}) rectangle ++(1,1);")
    for p, q in E:
        out.append(f"  \\draw[deleted, thick] ({p[0]},{p[1]}) -- ({q[0]},{q[1]});")
    for (i, j) in T:
        out.append(f"  \\fill[deleted] ({i},{j}) circle (0.12);")
    for (i, j) in S:
        out.append(f"  \\fill[retained] ({i},{j}) circle (0.12);")
    out.append("  \\draw[retained, thick, dashed] " + " -- ".join(f"({p[0]},{p[1]})" for p in hS) + " -- cycle;")
    out.append("  \\draw[deleted, thick, dashed] " + " -- ".join(f"({p[0]},{p[1]})" for p in hT) + " -- cycle;")
    out.append(r"\end{tikzpicture}")
    OUT["fig_boundary.tex"] = "\n".join(out) + "\n"
    return dict(S=len(S), T=len(T), holes=len(holes))


