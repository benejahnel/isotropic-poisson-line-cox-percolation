# Figure 2: initial construction (Proposition 3.1), L = r = 1, h = 1/8
# ---------------------------------------------------------------------------
def seg_box(p, q, xmin, xmax, ymin, ymax):
    """Liang--Barsky: does the closed segment pq meet the closed box?"""
    t0, t1 = 0.0, 1.0
    dx, dy = q[0] - p[0], q[1] - p[1]
    for pp, qq in ((-dx, p[0] - xmin), (dx, xmax - p[0]), (-dy, p[1] - ymin), (dy, ymax - p[1])):
        if pp == 0:
            if qq < 0:
                return False
        else:
            t = qq / pp
            if pp < 0:
                t0 = max(t0, t)
            else:
                t1 = min(t1, t)
            if t0 > t1:
                return False
    return True


def fig_polygon(seed=3):
    rng = random.Random(seed)
    L, r = 1.0, 1.0
    h = r / 8
    eta_fig = 0.05  # slopes enlarged from eta = 1/100 for visibility
    # (a, b): top/bottom y = a + b x, right/left x = a + b y
    aT, bT = 1.45, 0.04
    aB, bB = -1.43, -0.03
    aR, bR = 1.47, -0.035
    aL, bL = -1.42, 0.045
    for a, b, lo, hi in ((aT, bT, 1.4, 1.5), (aB, bB, -1.5, -1.4), (aR, bR, 1.4, 1.5), (aL, bL, -1.5, -1.4)):
        assert lo <= a <= hi and abs(b) <= eta_fig

    def inside(w):
        x, y = w
        return (y <= aT + bT * x + 1e-12 and y >= aB + bB * x - 1e-12
                and x <= aR + bR * y + 1e-12 and x >= aL + bL * y - 1e-12)

    # vertices: intersect consecutive lines (T&R, R&B, B&L, L&T)
    def hv(a1, b1, a2, b2):  # y = a1 + b1 x, x = a2 + b2 y
        y = (a1 + b1 * a2) / (1 - b1 * b2)
        return (a2 + b2 * y, y)

    V = [hv(aT, bT, aR, bR), hv(aB, bB, aR, bR), hv(aB, bB, aL, bL), hv(aT, bT, aL, bL)]
    # checks of the inclusions Q_{1.3L} in int P and P in Q_{1.6L}
    for x in (-1.3, 1.3):
        for y in (-1.3, 1.3):
            assert inside((x, y))
    assert max(max(abs(v[0]), abs(v[1])) for v in V) <= 1.6
    edges = [(V[i], V[(i + 1) % 4]) for i in range(4)]
    # chords in Q_{2L}
    chords = [((-2, aT - 2 * bT), (2, aT + 2 * bT)), ((-2, aB - 2 * bB), (2, aB + 2 * bB)),
              ((aR - 2 * bR, -2), (aR + 2 * bR, 2)), ((aL - 2 * bL, -2), (aL + 2 * bL, 2))]
    pts = []
    for p, q in chords:
        ell = math.dist(p, q)
        N = math.ceil(16 * ell / r)
        for k in range(N):
            t = (k + rng.random()) / N
            pts.append((p[0] + t * (q[0] - p[0]), p[1] + t * (q[1] - p[1])))
    # tiles meeting Gamma
    tiles = []
    m = int(round(2 * L / h))
    for i in range(-m, m + 1):
        for j in range(-m, m + 1):
            z = (i * h, j * h)
            box = (z[0] - h / 2, z[0] + h / 2, z[1] - h / 2, z[1] + h / 2)
            if any(seg_box(p, q, *box) for p, q in edges):
                tiles.append(z)
    assert all(max(abs(z[0]), abs(z[1])) <= 1.6 * L + h / 2 < 2 * L for z in tiles)
    out = [r"% Generated by make_figures.py (fig_polygon) -- do not edit by hand.",
           r"% L = r = 1, h = 1/8; slopes enlarged to at most 1/20 (inclusions re-checked).",
           r"\begin{tikzpicture}[x=2.1cm,y=2.1cm]"]
    for z in tiles:
        out.append(f"  \\fill[retainedfill!55] ({f(z[0]-h/2)},{f(z[1]-h/2)}) rectangle ++({h},{h});")
    for z in tiles:
        out.append(f"  \\draw[retained!50, very thin] ({f(z[0]-h/2)},{f(z[1]-h/2)}) rectangle ++({h},{h});")
    out.append(r"  \draw[gray, dashed] (-1,-1) rectangle (1,1);")
    out.append(r"  \draw[gray, densely dotted] (-1.3,-1.3) rectangle (1.3,1.3);")
    out.append(r"  \draw[gray, densely dotted] (-1.6,-1.6) rectangle (1.6,1.6);")
    out.append(r"  \draw[thick] (-2,-2) rectangle (2,2);")
    for p, q in chords:
        out.append(f"  \\draw[gray!80, thin] ({f(p[0])},{f(p[1])}) -- ({f(q[0])},{f(q[1])});")
    poly = " -- ".join(f"({f(v[0])},{f(v[1])})" for v in V) + " -- cycle"
    out.append(f"  \\draw[retained, very thick] {poly};")
    for x, y in pts:
        out.append(f"  \\fill[black] ({f(x)},{f(y)}) circle (0.018);")
    out += [r"  \node[font=\small, fill=white, inner sep=1pt] at (0,0) {$Q_L$};",
            r"  \node[font=\small, fill=white, inner sep=1pt] at (0,0.7) {$P$};",
            r"  \node[font=\small, anchor=north east] at (2,2) {$Q_{2L}$};",
            r"  \node[font=\scriptsize, anchor=south west, fill=white, inner sep=1pt] at (-1.3,-1.27) {$Q_{1.3L}$};",
            r"  \node[font=\scriptsize, anchor=south west, fill=white, inner sep=1pt] at (-1.6,-1.97) {$Q_{1.6L}$};",
            r"  \node[font=\small, anchor=west] at (2.02,1.53) {$\mathcal F_T$};",
            r"  \node[font=\small, anchor=west] at (2.02,-1.49) {$\mathcal F_B$};",
            r"  \node[font=\small, anchor=south] at (1.40,2.02) {$\mathcal F_R$};",
            r"  \node[font=\small, anchor=south] at (-1.33,2.02) {$\mathcal F_L$};",
            r"\end{tikzpicture}"]
    OUT["fig_polygon.tex"] = "\n".join(out) + "\n"
    return dict(tiles=len(tiles), pts=len(pts))


