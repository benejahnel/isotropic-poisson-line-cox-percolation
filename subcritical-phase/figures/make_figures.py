#!/usr/bin/env python3
r"""Generate fig_bundle.tex (run inside figures/).

Numerical illustration of Proposition 4.1: K lines crossing the strip
R = [0, d] x [0, a] (a = r/2, d = (m+1) r/2) through the middle halves of its
two vertical sides with slopes at most a/(4d) put Cox points into every box of
side r/2; consecutive chosen points are at distance < 2r.
"""
import math
import random


def f(x):
    return f"{x:.4f}"


def main(seed=4, r=1.0, m=8, K=5, lam=3.0):
    rng = random.Random(seed)
    a = r / 2
    d = (m + 1) * r / 2
    lines = []
    for _ in range(K):
        y0 = rng.uniform(a / 4, 3 * a / 4)
        b = rng.uniform(-a / (4 * d), a / (4 * d))
        lines.append((y0, b))
        # the line stays in the strip
        assert 0 <= y0 <= a and 0 <= y0 + b * d <= a
    pts = []  # (x, y, box index)
    for y0, b in lines:
        length = d * math.sqrt(1 + b * b)
        t = 0.0
        while True:
            t += rng.expovariate(lam)
            if t > length:
                break
            x = t / math.sqrt(1 + b * b)
            pts.append((x, y0 + b * x, min(int(x // a), m)))
    chosen = []
    for k in range(m + 1):
        inbox = [p for p in pts if p[2] == k]
        assert inbox, "box without point; change seed"
        chosen.append(min(inbox, key=lambda p: abs(p[1] - a / 2)))
    for p, q in zip(chosen, chosen[1:]):
        assert math.dist(p[:2], q[:2]) < 2 * r
    out = [r"% Generated by make_figures.py -- do not edit by hand.",
           f"% seed={seed}, r={r}, m={m}, K={K}, lambda={lam}",
           r"\begin{tikzpicture}[x=2.3cm,y=2.3cm]"]
    for k in range(m + 1):
        out.append(f"  \\draw[gray!60] ({f(k*a)},0) rectangle ({f((k+1)*a)},{f(a)});")
    out.append(f"  \\draw[deleted, line width=1.6pt] (0,{f(a/4)}) -- (0,{f(3*a/4)});")
    out.append(f"  \\draw[deleted, line width=1.6pt] ({f(d)},{f(a/4)}) -- ({f(d)},{f(3*a/4)});")
    for y0, b in lines:
        out.append(f"  \\draw[gray!80, thin] (-0.15,{f(y0-0.15*b)}) -- ({f(d+0.15)},{f(y0+(d+0.15)*b)});")
    for x, y, _ in pts:
        out.append(f"  \\fill[gray!70!black] ({f(x)},{f(y)}) circle (0.02);")
    chain = " -- ".join(f"({f(p[0])},{f(p[1])})" for p in chosen)
    out.append(f"  \\draw[retained, thick] {chain};")
    for x, y, _ in chosen:
        out.append(f"  \\fill[retained] ({f(x)},{f(y)}) circle (0.03);")
    out.append(f"  \\draw[|-|] (0,-0.12) -- ({f(a)},-0.12) node[midway, below, font=\\small] {{$r/2$}};")
    out.append(f"  \\node[font=\\small, anchor=east] at (-0.17,{f(a/2)}) {{$R$}};")
    out.append(r"\end{tikzpicture}")
    with open("fig_bundle.tex", "w") as fh:
        fh.write("\n".join(out) + "\n")
    print(len(pts), "points")


if __name__ == "__main__":
    main()
